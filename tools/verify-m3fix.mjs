// Runner-owned checks: no git operation or network.
import {spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {performance} from 'node:perf_hooks';
mkdirSync('docs/evidence',{recursive:true});
const commands=[['tests','npm test'],['digest','npm run digest'],
  ...['report','ensemble','signatures','projection-cell','projection-cell-domain','projection-year','projection-year-tree'].map(n=>[n,`node --test tests/${n}.test.mjs`]),
  ['kremer','node tools/m3fix-kremer.mjs'],['ensemble-64','npm run scenario -- --ensemble 64']];
const records=[];let failed=false;
for(const [name,command] of commands){
  // Test-only edits need fresh checks, not another unchanged simulation panel.
  if(process.argv.includes('--checks-only')&&['kremer','ensemble-64'].includes(name)){
    const old=readFileSync(`docs/evidence/m3fix-${name}.txt`,'utf8');
    const exit=Number(old.match(/\nExit: (\d+)/)[1]),wall=old.match(/\nWall ms: ([\d.]+)/)[1];
    const stdout=old.slice(old.indexOf('\n')+1,old.indexOf('\nExit:')).split('Seed wall ms:')[0];
    records.push({name,command,exit,wall,stdout});if(exit!==0)failed=true;
    console.log(`Retained unchanged simulation evidence: ${command}; exit ${exit}; wall ${wall} ms.`);continue;
  }
  const start=performance.now(),r=spawnSync('cmd.exe',['/d','/c',command],{encoding:'utf8',maxBuffer:30*1024*1024}),wall=(performance.now()-start).toFixed(2);
  const transcript=`$ ${command}\n${r.stdout??''}${r.stderr??''}\nExit: ${r.status}\nWall ms: ${wall}\n`;
  writeFileSync(`docs/evidence/m3fix-${name}.txt`,transcript);process.stdout.write(transcript);
  records.push({name,command,exit:r.status,wall,stdout:r.stdout??''});
  if(r.status!==0||['report','ensemble','signatures','projection-cell','projection-cell-domain','projection-year','projection-year-tree'].includes(name)&&Number(wall)>=2000)failed=true;
  if(name==='digest'&&!r.stdout?.includes('c3d614d0bbd2be2b3745ffaf766041d45671d99bb8770a8e7dbde7f9fd6510dc'))failed=true;
  if(name==='ensemble-64'&&r.status===0)copyFileSync('out/report.md','docs/evidence/m3fix-report.md');
}
const suite=records.find(r=>r.name==='tests'),ensemble=records.find(r=>r.name==='ensemble-64');
const lines=['### Runner observations (generated by tools/verify-m3fix.mjs)','',`Command checks and modified-file timing limits: ${failed?'NOT MET':'MET'}. Raw exit codes and timing limits follow.`,'',
  ...records.map(r=>`- \`${r.command}\`: exit ${r.exit}; process wall ${r.wall} ms. [Raw transcript](evidence/m3fix-${r.name}.txt).`),
  '', 'Exact npm test summary:', '```text',suite.stdout.split(/\r?\n/).filter(l=>/(?:tests |suites |pass |fail |cancelled |skipped |todo |duration_ms )/.test(l)).slice(-8).join('\n'),'```',
  '', 'Exact ensemble aggregate and SVG file list:', '```text',ensemble.stdout.includes('Aggregate (')?ensemble.stdout.slice(ensemble.stdout.indexOf('Aggregate (')):'No aggregate observed.','```'];
try{const k=JSON.parse(readFileSync('docs/evidence/m3fix-kremer.json','utf8'));lines.push('', 'Kremer status: '+k.status, '```json',JSON.stringify(k.summary??{},null,2),'```',k.conclusion??'No observed conclusion.');}catch{lines.push('Kremer evidence unavailable.');failed=true;}
const handoff='docs/m3-implementation.md',marker='<!-- M3FIX-RUNNER-OBSERVATIONS -->';
writeFileSync(handoff,readFileSync(handoff,'utf8').split(marker)[0]+marker+'\n'+lines.join('\n')+'\n');
process.exitCode=failed?1:0;
